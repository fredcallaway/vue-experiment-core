<script lang="ts" setup>
import { getConditionAssignmentCount, getConditionsForAssignment } from '../../utils/conditions'
import DocsPage from './DocsPage.vue'

const design = {
  main: {
    treatment: ['control', 'treatment'],
  },
  counterbalance: {
    taskOrder: ['AB', 'BA'],
    responseSide: ['left', 'right'],
  },
} as const

const assignments = Array.from({ length: getConditionAssignmentCount(design) }, (_, assignment) => ({
  assignment,
  ...getConditionsForAssignment(assignment, design),
}))
</script>

<template>
  <DocsPage name="conditions">
    <h3>Conditions</h3>
    <p>
      A <b>condition</b> is a between-subject choice: it's fixed for a participant for the
      whole session, and balanced across participants. Assign them in one place — usually your
      project's config composable — so that every session decodes its assignment the same way.
    </p>
    <p>
      Declare experimental manipulations as <code>main</code> conditions and nuisance variables such as task order or
      response mapping as <code>counterbalance</code> conditions.
    </p>
    <pre bg-gray-50 b="1 gray-200" rounded p3 text-sm overflow-x-auto><code>const conditions = useConditions().assign({
  main: {
    treatment: ['control', 'treatment'],
  },
  counterbalance: {
    taskOrder: ['AB', 'BA'],
    responseSide: ['left', 'right'],
  },
})</code></pre>
    <div
      mt-1
      h-56
      max-w-full
      overflow-auto
      b="1 gray-200"
      rounded
      tabindex="0"
      aria-label="Generated condition assignments"
    >
      <table text-sm min-w-120 w-full>
        <thead sticky top-0 z-1 bg-gray-50>
          <tr>
            <th p2 text-left>Assignment</th>
            <th p2 text-left>Treatment</th>
            <th p2 text-left>Task order</th>
            <th p2 text-left>Response side</th>
          </tr>
        </thead>
        <tbody>
          <tr v-for="row in assignments" :key="row.assignment" b-t="1 gray-100">
            <td p2>{{ row.assignment }}</td>
            <td p2>{{ row.treatment }}</td>
            <td p2>{{ row.taskOrder }}</td>
            <td p2>{{ row.responseSide }}</td>
          </tr>
        </tbody>
      </table>
    </div>
    <p>
      We iterate through all "main" conditions before selecting another counterbalance
      combination. We iterate through "counterbalance" combinations to minimize marginal imbalance in case
      you don't run enough participants to cover all possible combinations.
      The assignment index is taken from a URL parameter; this is handled automatically by our prolific interface.
    </p>
    <p>
      The table above is generated by <code>getConditionsForAssignment()</code> — the same pure
      helper <code>assign()</code> uses — so it reflects the real implementation rather than a
      hand-written copy of it. You can call it yourself when planning a design, to check how
      many participants a full pass through your grid takes.
    </p>

    <h3>Pinning a condition</h3>
    <p>
      Conditions are the thing you most need to override while developing: you want to see the
      treatment arm without reloading eight times. The condition inspector in
      <NuxtLink to="/dev">/dev</NuxtLink> lists every registered condition and lets you pin
      one. A pinned value is written to a <code>condition.&lt;key&gt;</code> URL parameter, so
      the pin survives a reload and can be shared as a link.
    </p>
    <p>
      Pinned conditions are excluded from the assignment counter: the un-pinned ones keep
      cycling normally, so you can hold <code>treatment</code> fixed and still step through
      every counterbalance.
    </p>
    <p>
      Conditions typically feed into params — see the
      <NuxtLink to="/examples/configuration">configuration example</NuxtLink>, which assigns a
      design and feeds the resulting values into component params.
    </p>
  </DocsPage>
</template>
