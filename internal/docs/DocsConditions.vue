<script lang="ts" setup>
import { getConditionAssignmentCount, getConditionsForAssignment } from '../../utils/conditions'
import DocsPage from './DocsPage.vue'

const design = {
  treatment: ['control', 'treatment'],
  taskOrder: ['AB', 'BA'],
  responseSide: ['left', 'right'],
} as const

const assignments = Array.from({ length: getConditionAssignmentCount(design) }, (_, assignment) => ({
  assignment,
  ...getConditionsForAssignment(assignment, design),
}))
</script>

<template>
  <ESequence name="conditions">
    <DocsPage name="intro">
      <h2>Conditions</h2>
      <p>
        A <b>condition</b> is a between-subject choice: it's fixed for a participant for the
        whole session, and balanced across assignment IDs. Pass all factors together to
        <code>assign()</code>, usually in <code>Experiment.vue</code>, so the schedule includes the complete design.
      </p>
      <p>
        Each key names a factor and its array lists the possible values. The returned object contains this
        participant's assigned values. Task orders can be supplied as array values, just like any other factor.
      </p>
      <DemoCode code="
        const conditions = useConditions().assign({
          treatment: ['control', 'treatment'],
          taskOrder: ['AB', 'BA'],
          responseSide: ['left', 'right'],
        })
      " />
    </DocsPage>

    <DocsPage name="balance">
      <h2>Balancing assignments</h2>
      <div
        class="mt-1 h-56 max-w-full overflow-auto b-1 b-gray-200 rounded"
        tabindex="0"
        aria-label="Generated condition assignments"
      >
        <table class="text-sm min-w-120 w-full">
          <thead class="sticky top-0 z-1 bg-gray-50">
            <tr>
              <th class="p2 text-left">Assignment</th>
              <th class="p2 text-left">Treatment</th>
              <th class="p2 text-left">Task order</th>
              <th class="p2 text-left">Response side</th>
            </tr>
          </thead>
          <tbody>
            <tr class="b-t-1 b-t-gray-100" v-for="row in assignments" :key="row.assignment">
              <td class="p2">{{ row.assignment }}</td>
              <td class="p2">{{ row.treatment }}</td>
              <td class="p2">{{ row.taskOrder }}</td>
              <td class="p2">{{ row.responseSide }}</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p>
        Every full combination appears once before the schedule repeats. For consecutive assignment IDs starting
        at zero, each factor's level counts differ by at most one at every prefix, including across repeated cycles.
        A pairwise heuristic chooses between balanced blocks to improve pair coverage while preserving that guarantee.
        It does not guarantee balanced interactions in small samples.
      </p>
      <p>
        The assignment ID comes from the URL; the Prolific interface supplies consecutive IDs. Missing or incomplete
        participants can unbalance the completed sample. Without an explicit assignment ID, a session-ID hash selects
        an assignment, so successive sessions do not necessarily follow the schedule in order.
      </p>
      <p>
        The table above is generated by <code>getConditionsForAssignment()</code> — the same pure
        helper <code>assign()</code> uses — so it reflects the real implementation rather than a
        hand-written copy of it. You can call it yourself when planning a design, to check how
        many participants a full pass through your grid takes.
      </p>
    </DocsPage>

    <DocsPage name="pinning">
      <h2>Pinning a condition</h2>
      <p>
        Conditions are the thing you most need to override while developing: you want to see the
        treatment arm without reloading eight times. The condition inspector in
        <NuxtLink to="/dev">/dev</NuxtLink> lists every registered condition and lets you pin
        one. A pinned value is written to a <code>condition.&lt;key&gt;</code> URL parameter, so
        the pin survives a reload and can be shared as a link.
      </p>
      <p>
        Pinned factors are excluded from the active design. The remaining factors keep their balanced schedule,
        so you can hold <code>treatment</code> fixed while exploring other conditions. Passing the complete design
        again, including after a component remount, reproduces the assignment for the same ID and pins.
      </p>
      <p>
        Conditions typically feed into params — see the
        <NuxtLink to="/examples/configuration">configuration example</NuxtLink>, which assigns a
        design and feeds the resulting values into component params.
      </p>
    </DocsPage>
  </ESequence>
</template>
